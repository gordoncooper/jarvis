"""An env's switches: the one short file naming what it enables, and the Flux wiring rendered from it.

CONTRACT: schema/CONTRACT.md. env-schema validates the names and compares the committed wiring;
render_switches.py writes it. The file holds names only: an app's settings stay in its app file.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path
from typing import Any

import yaml

from jarvis.lib import app_backups as _app_backups

# envs/<env>/values/switches.yaml.
SWITCHES_FILE = "values/switches.yaml"
# The features an env turns on. "optional" is the old name, read for one release.
FEATURES = "features"
LEGACY_FEATURES = "optional"
ADDONS = "addons"
APPS = "apps"
SECTIONS = (FEATURES, ADDONS, APPS)
# The rendered wiring, under envs/<env>/flux/.
ROOT_REL = "kustomization.yaml"
SERVICES_REL = "kustomizations/services.yaml"
SYNC_REL = "sync.yaml"
# Core's Flux base (the FluxInstance, identities and the platform layers), from an env's flux/.
CORE_FLUX_BASE = "../../../core/flux"
PLATFORM_CONFIGS_REL = "platform-configs/kustomization.yaml"
APP_HOSTING = "app-hosting"
APP_HOSTING_DIR = "core/feature/app-hosting"
OFFSITE_COPY = "offsite-backup-copy"
OFFSITE_COPY_DIR = "core/feature/offsite-backup-copy"
OFFSITE_SECRET_FILE = "backups-offsite.sops.yaml"
APPS_BACKUP_SERVER = "apps-backup-server"
# From an env's flux/platform-configs/ to the root artifact, which holds core/ and addons/.
_CORE_PATH = "../../../../"
# What each feature adds to the env's platform-configs. One name, one row.
# App DNS (k8s_gateway): the LAN resolves app hostnames through it. Off, the LAN's own DNS does.
APP_DNS = "app-dns"
APP_DNS_DIR = "core/feature/app-dns"
FEATURE_COMPONENTS: dict[str, dict[str, tuple[str, ...]]] = {
    APP_DNS: {"resources": (_CORE_PATH + APP_DNS_DIR,)},
    APP_HOSTING: {"components": (_CORE_PATH + APP_HOSTING_DIR,)},
    OFFSITE_COPY: {"resources": (_CORE_PATH + OFFSITE_COPY_DIR, f"../../secrets/{OFFSITE_SECRET_FILE}")},
    APPS_BACKUP_SERVER: {"resources": (_CORE_PATH + _app_backups.APPS_SERVER_DIR,)},
}
_BOOTSTRAP_RESOURCES = (
    _CORE_PATH + "core/platform/configs",
    "../../secrets/backups-restic.sops.yaml",
    "../../secrets/cert-manager-ca.sops.yaml",
)
_GENERATED_BY = "# Generated by tools/render from values/switches.yaml — do not edit.\n"


def load(env_dir: Path) -> tuple[dict[str, Any], list[str]]:
    """The env's switches as a mapping, or errors. A missing file is an empty mapping: env-schema
    requires the file once the env has a flux tree."""
    path = env_dir / SWITCHES_FILE
    if not path.is_file():
        return {}, []
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        return {}, [f"invalid YAML: {exc}"]
    if data is None:
        return {}, []
    if not isinstance(data, dict):
        return {}, [f"expected a mapping with {', '.join(SECTIONS)}"]
    if LEGACY_FEATURES in data:
        if FEATURES in data:
            return {}, [f"{FEATURES} and {LEGACY_FEATURES} both set; {LEGACY_FEATURES} is the old name of {FEATURES}, so keep only {FEATURES}"]
        data = {FEATURES if key == LEGACY_FEATURES else key: value for key, value in data.items()}
    return data, []


def names(data: dict[str, Any], section: str) -> list[str]:
    value = data.get(section)
    return [item for item in value if isinstance(item, str)] if isinstance(value, list) else []


def validate(data: dict[str, Any], addons: Sequence[str]) -> list[str]:
    """Each section is a list of names, each once, optional and addons only what core ships. Core
    itself is on in every env, so it has no section. _apps validates the shape of an app name."""
    errors = [f"unknown key {key!r} (allowed: {', '.join(SECTIONS)})" for key in sorted(set(data) - set(SECTIONS), key=str)]
    known = {FEATURES: tuple(FEATURE_COMPONENTS), ADDONS: addons}
    for section in SECTIONS:
        value = data.get(section)
        if value is None:
            value = []
        if not isinstance(value, list):
            errors.append(f"{section} must be a list of names")
            continue
        seen: set[str] = set()
        for item in value:
            if not isinstance(item, str):
                errors.append(f"{section}: {item!r} is not a name")
            elif section in known and item not in known[section]:
                errors.append(f"{section}: unknown name {item!r} (known: {', '.join(known[section]) or 'none'})")
            elif item in seen:
                errors.append(f"{section}: {item} is listed twice")
            else:
                seen.add(item)
    return errors


def _dump(doc: dict[str, Any], note: str = "") -> str:
    return _GENERATED_BY + note + yaml.safe_dump(doc, sort_keys=False, default_flow_style=False)


def platform_configs(data: dict[str, Any], *, extra_components: Sequence[str] = ()) -> str:
    """The env's platform-configs list: core configs, the two sealed files bootstrap-secrets writes,
    and what each listed feature adds. extra_components is the backup-selection wrapper."""
    resources: list[str] = list(_BOOTSTRAP_RESOURCES)
    components: list[str] = []
    enabled = names(data, FEATURES)
    for name, adds in FEATURE_COMPONENTS.items():
        if name in enabled:
            resources.extend(adds.get("resources", ()))
            components.extend(adds.get("components", ()))
    components.extend(extra_components)
    doc: dict[str, Any] = {
        "apiVersion": "kustomize.config.k8s.io/v1beta1",
        "kind": "Kustomization",
        "resources": resources,
    }
    if components:
        doc["components"] = components
    return _dump(doc)


def services(data: dict[str, Any]) -> str:
    """The services stage: it creates each listed add-on's namespaces and bindings, so it runs as
    the platform account. With no add-on listed the env is core-only."""
    spec: dict[str, Any] = {
        "interval": "10m",
        "retryInterval": "1m",
        "path": "./addons",
        "prune": True,
        "serviceAccountName": "flux-platform",
        "sourceRef": {"kind": "GitRepository", "name": "flux-system"},
        "dependsOn": [{"name": "platform-configs"}],
    }
    if names(data, ADDONS):
        spec["components"] = names(data, ADDONS)
    spec["postBuild"] = {"substituteFrom": [{"kind": "ConfigMap", "name": "cluster-vars"}]}
    doc = {
        "apiVersion": "kustomize.toolkit.fluxcd.io/v1",
        "kind": "Kustomization",
        "metadata": {"name": "services", "namespace": "flux-system"},
        "spec": spec,
    }
    return _dump(doc, "# The services stage applies each add-on's wiring from core, as the platform account.\n")


def root_kustomization(data: dict[str, Any], *, apps_generated: str) -> str:
    """The root Flux path's list; the app wiring render joins it once the env lists an app."""
    resources = [
        CORE_FLUX_BASE,
        "generated/cluster-vars-configmap.yaml",
        "sync.yaml",
        SERVICES_REL,
    ]
    if names(data, APPS):
        resources.append(apps_generated)
    return _dump({"apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization", "resources": resources})


_SYNC = """\
# Generated by tools/render from values/cluster-vars.yaml — do not edit.
# Ansible (flux-operator role) applies this file once on a new cluster; the flux-system
# Kustomization below then reconciles it from Git with the rest of this directory. The root
# source is the env repo (flux_git_repo_url, flux_git_ref). It includes the core source
# (core_git_repo_url, core_git_ref): its core/ and addons/ at core/ and addons/, so every Flux
# path here reads env files, core and add-ons from one artifact, with one decryptor.
apiVersion: source.toolkit.fluxcd.io/v1
kind: GitRepository
metadata:
  name: flux-system
  namespace: flux-system
  # The root Kustomization owns the sources; a bad commit that drops one must not remove Flux's own source.
  annotations:
    kustomize.toolkit.fluxcd.io/prune: disabled
spec:
  interval: 1m
  url: {root_url}
  ref:
    name: {root_ref}
{secret_ref}  include:
    - repository:
        name: core
      fromPath: core
      toPath: core
    - repository:
        name: core
      fromPath: addons
      toPath: addons
---
# Public core, read with no credential.
apiVersion: source.toolkit.fluxcd.io/v1
kind: GitRepository
metadata:
  name: core
  namespace: flux-system
  annotations:
    kustomize.toolkit.fluxcd.io/prune: disabled
spec:
  interval: 1m
  url: {core_url}
  ref:
    name: {core_ref}
---
apiVersion: kustomize.toolkit.fluxcd.io/v1
kind: Kustomization
metadata:
  name: flux-system
  namespace: flux-system
  # Deleting this object from Git must not prune the cluster it applies. The layer
  # Kustomizations keep prune on.
  annotations:
    kustomize.toolkit.fluxcd.io/prune: disabled
spec:
  interval: 10m
  path: ./envs/{env}/flux
  prune: true
  # The controller's own identity, as the operator's sync used. This path
  # declares the accounts every other Flux object runs as.
  serviceAccountName: kustomize-controller
  sourceRef:
    kind: GitRepository
    name: flux-system
  # Core's Flux base (core/flux) names this env's paths by it.
  postBuild:
    substitute:
      jarvis_env: {env}
"""

# An ssh:// root reads with the sealed read-only deploy key (secrets/flux-deploy-key.sops.yaml),
# which Ansible applies once.
_DEPLOY_KEY_REF = "  secretRef:\n    name: flux-deploy-key\n"


def sync(cluster_vars: dict[str, Any], env: str) -> str:
    """flux/sync.yaml: the root and core sources and the root Kustomization, from cluster-vars."""
    root_url = str(cluster_vars.get("flux_git_repo_url") or "")
    return _SYNC.format(
        root_url=root_url,
        root_ref=cluster_vars.get("flux_git_ref") or "",
        core_url=cluster_vars.get("core_git_repo_url") or "",
        core_ref=cluster_vars.get("core_git_ref") or "",
        secret_ref=_DEPLOY_KEY_REF if root_url.startswith("ssh://") else "",
        env=env,
    )
