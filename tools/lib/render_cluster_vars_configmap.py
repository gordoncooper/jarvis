#!/usr/bin/env python3
"""Render flux-system/cluster-vars ConfigMap from envs/<env>/values/cluster-vars.yaml (R4).

Lists and maps are JSON-encoded strings so postBuild substitution can reference them
without duplicating keys outside values/cluster-vars.yaml.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from schema.env import resolve_cluster_vars  # noqa: E402


def _flatten_value(value: Any) -> str:
    if isinstance(value, (list, dict)):
        return json.dumps(value, separators=(",", ":"))
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return ""
    return str(value)


def cluster_vars_configmap(
    cluster_vars: dict[str, Any],
    *,
    namespace: str = "flux-system",
    name: str = "cluster-vars",
) -> dict[str, Any]:
    resolved = resolve_cluster_vars(cluster_vars)
    return {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": {"name": name, "namespace": namespace},
        "data": {key: _flatten_value(value) for key, value in resolved.items()},
    }


def render_document(cluster_vars_path: Path) -> str:
    raw = yaml.safe_load(cluster_vars_path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise SystemExit(f"{cluster_vars_path}: expected mapping at top level")
    doc = cluster_vars_configmap(raw)
    header = (
        "# Generated by tools/lib/render_cluster_vars_configmap.py — do not edit.\n"
        "# Source: values/cluster-vars.yaml (R4 postBuild substituteFrom).\n"
    )
    body = yaml.safe_dump(
        doc,
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=True,
    )
    return header + body


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--env", required=True, help="Env name under envs/")
    parser.add_argument(
        "--output",
        type=Path,
        help="Write file instead of stdout",
    )
    args = parser.parse_args(argv)

    env_name = args.env
    cluster_vars_path = REPO_ROOT / "envs" / env_name / "values" / "cluster-vars.yaml"
    if not cluster_vars_path.is_file():
        raise SystemExit(f"missing {cluster_vars_path}")

    text = render_document(cluster_vars_path)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
