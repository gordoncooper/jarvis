"""An env's switches: the one short file naming what it enables, and the Flux wiring rendered from it.

CONTRACT: schema/CONTRACT.md. env-schema validates the names and compares the committed wiring;
render_switches.py writes it. The file holds names only: an app's settings stay in its app file.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Sequence

import yaml

import _app_backups  # noqa: E402

# envs/<env>/values/switches.yaml.
SWITCHES_FILE = "values/switches.yaml"
OPTIONAL = "optional"
ADDONS = "addons"
APPS = "apps"
SECTIONS = (OPTIONAL, ADDONS, APPS)
# The rendered wiring, under envs/<env>/flux/.
ROOT_REL = "kustomization.yaml"
SERVICES_REL = "kustomizations/services.yaml"
PLATFORM_CONFIGS_REL = "platform-configs/kustomization.yaml"
APP_HOSTING = "app-hosting"
APP_HOSTING_DIR = "platform/optional/app-hosting"
OFFSITE_COPY = "offsite-backup-copy"
OFFSITE_COPY_DIR = "platform/optional/offsite-backup-copy"
OFFSITE_SECRET_FILE = "backups-offsite.sops.yaml"
APPS_BACKUP_SERVER = "apps-backup-server"
_CORE_PATH = "../../../../core/"
# What each optional core component adds to the env's platform-configs. One name, one row.
OPTIONAL_COMPONENTS: dict[str, dict[str, tuple[str, ...]]] = {
    APP_HOSTING: {"components": (_CORE_PATH + APP_HOSTING_DIR,)},
    OFFSITE_COPY: {"resources": (_CORE_PATH + OFFSITE_COPY_DIR, f"../../secrets/{OFFSITE_SECRET_FILE}")},
    APPS_BACKUP_SERVER: {"resources": (_CORE_PATH + _app_backups.APPS_SERVER_DIR,)},
}
_BOOTSTRAP_RESOURCES = (
    _CORE_PATH + "platform/configs",
    "../../secrets/backups-restic.sops.yaml",
    "../../secrets/cert-manager-ca.sops.yaml",
)
_GENERATED_BY = "# Generated by tools/lib/render_switches.py from values/switches.yaml — do not edit.\n"


def load(env_dir: Path) -> tuple[dict[str, Any], list[str]]:
    """The env's switches as a mapping, or errors. A missing file is an empty mapping: env-schema
    requires the file once the env has a flux tree."""
    path = env_dir / SWITCHES_FILE
    if not path.is_file():
        return {}, []
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        return {}, [f"invalid YAML: {exc}"]
    if data is None:
        return {}, []
    if not isinstance(data, dict):
        return {}, [f"expected a mapping with {', '.join(SECTIONS)}"]
    return data, []


def names(data: dict[str, Any], section: str) -> list[str]:
    value = data.get(section)
    return [item for item in value if isinstance(item, str)] if isinstance(value, list) else []


def validate(data: dict[str, Any], addons: Sequence[str]) -> list[str]:
    """Each section is a list of names, each once, optional and addons only what core ships. Core
    itself is on in every env, so it has no section. _apps validates the shape of an app name."""
    errors = [f"unknown key {key!r} (allowed: {', '.join(SECTIONS)})" for key in sorted(set(data) - set(SECTIONS), key=str)]
    known = {OPTIONAL: tuple(OPTIONAL_COMPONENTS), ADDONS: addons}
    for section in SECTIONS:
        value = data.get(section)
        if value is None:
            value = []
        if not isinstance(value, list):
            errors.append(f"{section} must be a list of names")
            continue
        seen: set[str] = set()
        for item in value:
            if not isinstance(item, str):
                errors.append(f"{section}: {item!r} is not a name")
            elif section in known and item not in known[section]:
                errors.append(f"{section}: unknown name {item!r} (known: {', '.join(known[section]) or 'none'})")
            elif item in seen:
                errors.append(f"{section}: {item} is listed twice")
            else:
                seen.add(item)
    return errors


def _dump(doc: dict[str, Any], note: str = "") -> str:
    return _GENERATED_BY + note + yaml.safe_dump(doc, sort_keys=False, default_flow_style=False)


def platform_configs(data: dict[str, Any], *, extra_components: Sequence[str] = ()) -> str:
    """The env's platform-configs list: core configs, the two sealed files bootstrap-secrets writes,
    and what each listed optional component adds. extra_components is the backup-selection wrapper."""
    resources = list(_BOOTSTRAP_RESOURCES)
    components: list[str] = []
    enabled = names(data, OPTIONAL)
    for name, adds in OPTIONAL_COMPONENTS.items():
        if name in enabled:
            resources.extend(adds.get("resources", ()))
            components.extend(adds.get("components", ()))
    components.extend(extra_components)
    doc: dict[str, Any] = {
        "apiVersion": "kustomize.config.k8s.io/v1beta1",
        "kind": "Kustomization",
        "resources": resources,
    }
    if components:
        doc["components"] = components
    return _dump(doc)


def services(data: dict[str, Any]) -> str:
    """The services stage: it creates each listed add-on's namespaces and bindings, so it runs as
    the platform account. With no add-on listed the env is core-only."""
    spec: dict[str, Any] = {
        "interval": "10m",
        "retryInterval": "1m",
        "path": "./core/services",
        "prune": True,
        "serviceAccountName": "flux-platform",
        "sourceRef": {"kind": "GitRepository", "name": "flux-system"},
        "dependsOn": [{"name": "platform-configs"}],
    }
    if names(data, ADDONS):
        spec["components"] = names(data, ADDONS)
    spec["postBuild"] = {"substituteFrom": [{"kind": "ConfigMap", "name": "cluster-vars"}]}
    doc = {
        "apiVersion": "kustomize.toolkit.fluxcd.io/v1",
        "kind": "Kustomization",
        "metadata": {"name": "services", "namespace": "flux-system"},
        "spec": spec,
    }
    return _dump(doc, "# The services stage applies each add-on's wiring from core, as the platform account.\n")


def root_kustomization(data: dict[str, Any], *, apps_generated: str) -> str:
    """The root Flux path's list; the app wiring render joins it once the env lists an app."""
    resources = [
        "generated/cluster-vars-configmap.yaml",
        "flux-instance.yaml",
        "sync.yaml",
        "identities.yaml",
        "kustomizations/platform-controllers.yaml",
        "kustomizations/platform-configs.yaml",
        SERVICES_REL,
        "kustomizations/apps.yaml",
    ]
    if names(data, APPS):
        resources.append(apps_generated)
    return _dump({"apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization", "resources": resources})
